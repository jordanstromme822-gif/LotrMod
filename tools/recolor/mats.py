def ramp(name, L):
    k = np.array(M[name]); Ls = k[:, 0]
    a = np.cos(np.radians(k[:, 1])) * k[:, 2]; b = np.sin(np.radians(k[:, 1])) * k[:, 2]
    aa = np.interp(L, Ls, a); bb = np.interp(L, Ls, b)
    return np.degrees(np.arctan2(bb, aa)) % 360, np.hypot(aa, bb)
